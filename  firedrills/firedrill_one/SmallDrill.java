public class SmallDrill {
  public static void main(String[] args) {

    for(int counter = 10; counter > 0; counter--) {
      System.out.println("Launching " + counter);
      if(counter == 5) {
        System.out.println("HALFWAY TO THE LAUNCH");
      } 
    System.out.print("Go Again,Enter Y/N:");
    if(counter.equals(9));
      System.out.println(counter);
    }

  }
}
